def main():
    print("=" * 70)
    print("KHOJ MUMBAI: Seeding Batch 2 Malls, Food Courts & Fast-Food Outlets")
    print("=" * 70)

    base_dir = os.path.dirname(__file__)
    data_dir = os.path.join(base_dir, "..", "data", "places_mumbai")
    os.makedirs(data_dir, exist_ok=True)
    
    malls_file = os.path.join(data_dir, "youth_hangouts.json")
    fastfood_file = os.path.join(data_dir, "fastfood.json")
    master_file = os.path.join(base_dir, "..", "data", "places_mumbai.json")

    # 1. Non-destructively append new malls to youth_hangouts.json
    existing_malls = []
    if os.path.exists(malls_file):
        with open(malls_file, "r", encoding="utf-8") as f:
            existing_malls = json.load(f)
            
    existing_mall_ids = {m.get("id") for m in existing_malls}
    new_malls_added = 0
    for mall in BATCH2_MALLS:
        if mall["id"] not in existing_mall_ids:
            existing_malls.append(mall)
            existing_mall_ids.add(mall["id"])
            new_malls_added += 1

    with open(malls_file, "w", encoding="utf-8") as f:
        json.dump(existing_malls, f, indent=2, ensure_ascii=False)
    print(f"✓ Added {new_malls_added} new major malls to {malls_file} (Total malls/hubs: {len(existing_malls)})")

    # 2. Non-destructively append standalone fast-food outlets to fastfood.json
    existing_ff = []
    if os.path.exists(fastfood_file):
        with open(fastfood_file, "r", encoding="utf-8") as f:
            existing_ff = json.load(f)
            
    existing_ff_ids = {f.get("id") for f in existing_ff}
    new_ff_added = 0
    for outlet in BATCH2_STANDALONE_FASTFOOD:
        if outlet["id"] not in existing_ff_ids:
            existing_ff.append(outlet)
            existing_ff_ids.add(outlet["id"])
            new_ff_added += 1

    with open(fastfood_file, "w", encoding="utf-8") as f:
        json.dump(existing_ff, f, indent=2, ensure_ascii=False)
    print(f"✓ Added {new_ff_added} new standalone fast-food outlets to {fastfood_file} (Total standalone: {len(existing_ff)})")

    # 3. Synchronize all into master places_mumbai.json
    if os.path.exists(master_file):
        with open(master_file, "r", encoding="utf-8") as f:
            master_places = json.load(f)
            
        master_ids = {p.get("id") for p in master_places}
        total_master_added = 0

        for item in BATCH2_MALLS + BATCH2_STANDALONE_FASTFOOD:
            if item["id"] not in master_ids:
                master_places.append(item)
                master_ids.add(item["id"])
                total_master_added += 1

        with open(master_file, "w", encoding="utf-8") as f:
            json.dump(master_places, f, indent=2, ensure_ascii=False)
        print(f"✓ Synchronized {total_master_added} new records into master {master_file}")
        print(f"  🎉 Grand Total Places in Database: {len(master_places)}")

