def add_places():
    total_added = 0
    all_places = []
    
    # 1. Process each category
    for cat, items in EXPANDED_PLACES.items():
        cat_file = os.path.join(DATA_DIR, f"{cat}.json")
        existing = []
        if os.path.exists(cat_file):
            try:
                with open(cat_file, 'r', encoding='utf-8') as f:
                    existing = json.load(f)
            except Exception:
                existing = []
        
        existing_ids = {p['id'] for p in existing}
        cat_added = 0
        for item in items:
            if item['id'] not in existing_ids:
                existing.append(item)
                existing_ids.add(item['id'])
                cat_added += 1
                total_added += 1
        
        with open(cat_file, 'w', encoding='utf-8') as f:
            json.dump(existing, f, indent=2, ensure_ascii=False)
        
        print(f"[*] Category '{cat.upper()}': Added {cat_added} new places. Total now: {len(existing)}")
    
    # 2. Gather all modular files for consolidated export
    for fname in os.listdir(DATA_DIR):
        if fname.endswith('.json'):
            fpath = os.path.join(DATA_DIR, fname)
            try:
                with open(fpath, 'r', encoding='utf-8') as f:
                    all_places.extend(json.load(f))
            except Exception as e:
                print(f"[!] Error reading {fname}: {e}")
                
    with open(COMBINED_FILE, 'w', encoding='utf-8') as f:
        json.dump(all_places, f, indent=2, ensure_ascii=False)
        
    print(f"\n=======================================================")
    print(f"[SUCCESS] Added {total_added} places across categories!")
    print(f"Total verified places in KHOJ Mumbai database: {len(all_places)}")
    print(f"=======================================================\n")


if __name__ == '__main__':
    add_places()

