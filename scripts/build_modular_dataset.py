def main():
    all_places = []
    
    # 1. Read existing cafes and forts
    for cat in ['cafes', 'forts']:
        cat_file = os.path.join(OUTPUT_DIR, f'{cat}.json')
        if os.path.exists(cat_file):
            with open(cat_file, 'r', encoding='utf-8') as f:
                items = json.load(f)
                all_places.extend(items)

    # 2. Write all other category files
    for cat, items in DATA.items():
        cat_file = os.path.join(OUTPUT_DIR, f'{cat}.json')
        with open(cat_file, 'w', encoding='utf-8') as f:
            json.dump(items, f, indent=2, ensure_ascii=False)
        all_places.extend(items)
        print(f'Wrote {len(items)} places to data/places_mumbai/{cat}.json')

    # 3. Synchronize combined data/places_mumbai.json
    with open(COMBINED_FILE, 'w', encoding='utf-8') as f:
        json.dump(all_places, f, indent=2, ensure_ascii=False)
    
    print(f'Total combined places across all 12 categories: {len(all_places)}')

if __name__ == '__main__':
    main()

